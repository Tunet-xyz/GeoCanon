def get_language_choices() -> list[tuple[str, Any]]:
    """Return language choices for a Django ``ChoiceField``."""
    return list(LANGUAGE_CHOICES)


def get_language_for_jurisdiction(jurisdiction: str) -> str | None:
    """
    Return the default ISO 639-1 language code for *jurisdiction*.

    Returns ``None`` if the jurisdiction has no language mapping.

    >>> get_language_for_jurisdiction("Romania")
    'ro'
    """
    return JURISDICTION_LANGUAGE.get(jurisdiction)
